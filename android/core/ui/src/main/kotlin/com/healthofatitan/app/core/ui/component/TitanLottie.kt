/**
 * Lottie of the Titan (Agent 17, D-037; brief docs/design/training/animator-brief.md), v2: the
 * Titan of the mark as a cut-out rig — the top-20 exercises and the 5 heroic moments, generated by
 * tools/lottie from the same key poses as the Compose rig. assets/lottie/manifest.json lists the
 * files with their markers. They live here, in core:ui, so the player and «Сегодня» share them.
 */
data class LottieEntry(
    val id: String,
    val file: String,
    val kind: String,
    val frames: Int,
    val markers: Map<String, Int>,
) {
    /** Progress (0…1) of a marker; the poster is the key pose for «Удалить анимацию». */
    fun at(marker: String): Float? = markers[marker]?.let { it.toFloat() / frames.coerceAtLeast(1) }

    val poster: Float get() = at("poster") ?: 0f

    /**
     * Progress at [ms] since the exercise started. Holds (stretches, breathing in place) play the
     * entry once and then loop between `hold_loop_start` and `hold_loop_end`; everything else
     * loops whole, stretched to [cycleMs] — the cycle of the user's tempo.
     */
    fun progress(ms: Long, cycleMs: Long): Float {
        val total = frames.toLong() * 1000L / FPS
        val loopStart = markers["hold_loop_start"]
        val loopEnd = markers["hold_loop_end"]
        if (loopStart != null && loopEnd != null && loopEnd > loopStart) {
            val startMs = loopStart * 1000L / FPS
            val loopMs = (loopEnd - loopStart) * 1000L / FPS
            val f = if (ms < startMs) ms * FPS / 1000.0 else loopStart + ((ms - startMs) % loopMs) * FPS / 1000.0
            return (f / frames).toFloat().coerceIn(0f, 1f)
        }
        val cycle = if (kind == "reps" && cycleMs > 0) cycleMs else total
        if (cycle <= 0) return 0f
        return ((ms % cycle).toFloat() / cycle).coerceIn(0f, 1f)
    }

    companion object {
        const val FPS = 60
    }
}

object TitanLottie {
    const val MANIFEST = "lottie/manifest.json"

    /** The heroic moments of the brief (Part 2). */
    const val HERO_SEAL = "hero-seal"
    const val HERO_LEVEL_UP = "hero-level-up"
    const val HERO_RECORD = "hero-record"
    const val HERO_FIRST_SKILL = "hero-first-skill"
    const val HERO_TEST_PASSED = "hero-test-passed"

    fun parse(json: String): Map<String, LottieEntry> {
        val files = JSONObject(json).optJSONObject("files") ?: return emptyMap()
        return files.keys().asSequence().mapNotNull { id ->
            val o = files.optJSONObject(id) ?: return@mapNotNull null
            val m = o.optJSONObject("markers")
            val markers = m?.keys()?.asSequence()?.associateWith { m.getInt(it) }.orEmpty()
            LottieEntry(id, o.getString("file"), o.optString("kind", "reps"), o.getInt("frames"), markers)
        }.associateBy { it.id }
    }

    @Volatile
    var cached: Map<String, LottieEntry>? = null
        private set

    fun load(context: Context): Map<String, LottieEntry> = cached ?: runCatching {
        context.assets.open(MANIFEST).bufferedReader().use { parse(it.readText()) }
    }.getOrDefault(emptyMap()).also { cached = it }

    /** The three stops of the light line (the files have three: white → mid → accent). */
    fun stops(light: List<Color>): Array<Int> = when {
        light.isEmpty() -> arrayOf(Color.White.toArgb(), Color.White.toArgb(), Color.White.toArgb())
        light.size == 1 -> Array(3) { light[0].toArgb() }
        light.size == 2 -> arrayOf(light[0].toArgb(), lerpColor(light[0], light[1]).toArgb(), light[1].toArgb())
        else -> arrayOf(light.first().toArgb(), light[light.size / 2].toArgb(), light.last().toArgb())
    }

    private fun lerpColor(a: Color, b: Color) = Color(
        red = (a.red + b.red) / 2, green = (a.green + b.green) / 2, blue = (a.blue + b.blue) / 2, alpha = (a.alpha + b.alpha) / 2,
    )
}

@Composable
fun rememberTitanLottie(): Map<String, LottieEntry> {
    val context = LocalContext.current
    val manifest by produceState(TitanLottie.cached ?: emptyMap(), context) {
        value = withContext(Dispatchers.IO) { TitanLottie.load(context.applicationContext) }
    }
    return manifest
}

/**
 * The Titan of a Lottie file, recoloured to the mode and the theme, mirrored for the other side.
 * [animate] false («Удалить анимацию», pause, countdown) shows the static key pose (`poster`).
 */
@Composable
fun TitanLottieFigure(
    entry: LottieEntry,
    cycleMs: Long,
    light: List<Color>,
    glow: Color?,
    accent: Color,
    modifier: Modifier = Modifier,
    animate: Boolean = true,
    mirrored: Boolean = false,
    description: String? = null,
) {
    val tokens = HotThemeTokens.colors
    val composition by rememberLottieComposition(LottieCompositionSpec.Asset(entry.file))
    val dynamic = rememberTitanColors(light, accent)
    val ms by produceState<Long?>(null, entry.id, animate) {
        value = null
        if (!animate) return@produceState
        val start = withFrameMillis { it }
        while (true) value = withFrameMillis { it } - start
    }
    val withGlow = glow?.takeIf { tokens.glow }
    val progress = { ms?.let { entry.progress(it, cycleMs) } ?: entry.poster }
    Box(modifier.semantics { if (description != null) contentDescription = description }) {
        if (withGlow != null) {
            Canvas(Modifier.fillMaxSize()) {
                val r = size.minDimension * 0.46f
                drawCircle(Brush.radialGradient(listOf(withGlow.copy(alpha = 0.22f), Color.Transparent), center = center, radius = r), r, center)
            }
        }
        val figure = Modifier.fillMaxSize().graphicsLayer { if (mirrored) scaleX = -1f }
        if (withGlow != null) LineGlow(composition, progress, figure, dynamic)
        LottieAnimation(composition = composition, progress = progress, modifier = figure, dynamicProperties = dynamic)
    }
}

/**
 * The glow of the line of light (the mark is drawn glowing): the same frame, blurred, under the
 * sharp one. RenderEffect blur needs Android 12; below it the figure is drawn without the glow.
 */
@Composable
private fun LineGlow(composition: LottieComposition?, progress: () -> Float, modifier: Modifier, dynamic: LottieDynamicProperties) {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.S) return
    LottieAnimation(
        composition = composition,
        progress = progress,
        modifier = modifier.blur(GLOW_RADIUS, BlurredEdgeTreatment.Unbounded).alpha(0.75f),
        dynamicProperties = dynamic,
    )
}

private val GLOW_RADIUS = 7.dp

/**
 * Mode and theme colours by layer name (the brief's contract): the light line gradient, the glass
 * knockout, inner strokes, props, floor, ring (and ring_next — the new level), columns.
 */
@Composable
private fun rememberTitanColors(light: List<Color>, accent: Color, next: Color = accent): LottieDynamicProperties {
    val tokens = HotThemeTokens.colors
    val stops = remember(light) { TitanLottie.stops(light) }
    val inner = (light.getOrNull(light.size / 2) ?: Color.White).toArgb()
    val knockout = tokens.knockout.toArgb()
    return rememberLottieDynamicProperties(
        rememberLottieDynamicProperty(LottieProperty.GRADIENT_COLOR, stops, "**", "titan_line", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, knockout, "**", "titan_knockout", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, inner, "**", "titan_inner", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, accent.toArgb(), "**", "props_line", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, tokens.hairline.toArgb(), "**", "floor", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, accent.toArgb(), "**", "ring", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, next.toArgb(), "**", "ring_next", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, inner, "**", "columns_line", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, inner, "**", "columns_flutes", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, knockout, "**", "columns_knockout", "**"),
    )
}

const val TITAN_HERO_TAG = "titan_hero"

/**
 * A heroic moment (brief Part 2: hero-seal, hero-level-up, hero-record, hero-first-skill,
 * hero-test-passed), played once per [key]; «Удалить анимацию» shows the final frame (the brief's
 * still). [next] is the colour of the new level for hero-level-up. The double tick of the seal
 * comes when the ring closes. While the manifest loads, or if the file is missing, [fallback]
 * draws instead (the Compose scene of before).
 */
@Composable
fun TitanHeroMoment(
    id: String,
    key: String,
    light: List<Color>,
    accent: Color,
    modifier: Modifier = Modifier,
    next: Color = accent,
    description: String? = null,
    fallback: @Composable () -> Unit = {},
) {
    val entry = rememberTitanLottie()[id]
    if (entry == null) {
        fallback()
        return
    }
    val animate = !rememberReduceMotion()
    val tokens = HotThemeTokens.colors
    val composition by rememberLottieComposition(LottieCompositionSpec.Asset(entry.file))
    val dynamic = rememberTitanColors(light, accent, next)
    val total = entry.frames * 1000L / LottieEntry.FPS
    val ms by produceState(0L, key, animate) {
        if (!animate) return@produceState
        val start = withFrameMillis { it }
        while (value < total) value = withFrameMillis { it } - start
    }
    val haptic = LocalHapticFeedback.current
    val tickAt = (entry.markers["seal"] ?: entry.markers["level"] ?: entry.markers["pause"])?.let { it * 1000L / LottieEntry.FPS }
    LaunchedEffect(key, animate, tickAt) {
        if (!animate || tickAt == null) return@LaunchedEffect
        delay(tickAt)
        haptic.performHapticFeedback(HapticFeedbackType.Confirm)
        delay(SECOND_TICK_MS)
        haptic.performHapticFeedback(HapticFeedbackType.Confirm)
    }
    val progress = { if (!animate) 1f else (ms.toFloat() / total).coerceIn(0f, 1f) }
    val figure = Modifier.fillMaxSize()
    Box(modifier.semantics { if (description != null) contentDescription = description }.testTag(TITAN_HERO_TAG)) {
        if (tokens.glow) LineGlow(composition, progress, figure, dynamic)
        LottieAnimation(composition = composition, progress = progress, modifier = figure, dynamicProperties = dynamic)
    }
}

private const val SECOND_TICK_MS = 90L

/**
 * «Печать» as the heroic moment H1 (the Titan straightens into the mark, the ring closes, the
 * double tick) — at the points where the Compose [TitanSeal] stood: «Сегодня» (WHOOP confirmed
 * the training) and «Итог» of the player. Without the file it is the Compose seal of before.
 * [moment] is one of the heroes of [TitanLottie]: «Итог» passes the record, the new level or the
 * passed test once the training engine reports them; the seal is the default.
 */
@Composable
fun TitanSealMoment(
    key: String,
    modifier: Modifier = Modifier,
    spoken: String = "Тренировку подтвердил WHOOP",
    moment: String = TitanLottie.HERO_SEAL,
    next: Color? = null,
) {
    val tokens = HotThemeTokens.colors
    val light = if (tokens.isDark) Titanium.LightIce else tokens.titanLight
    TitanHeroMoment(
        id = moment,
        key = key,
        light = light,
        accent = tokens.modeRovno,
        modifier = modifier,
        next = next ?: tokens.modeRovno,
        description = spoken,
        fallback = { TitanSeal(key = key, modifier = modifier, spoken = spoken) },
    )
}
