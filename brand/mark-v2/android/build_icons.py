def argb(hexcol, a=1.0):
    h = hexcol.lstrip('#')
    if len(h) == 3:
        h = ''.join(c * 2 for c in h)
    return '#%02X%s' % (round(a * 255), h.upper())


def write(name, text):
    with open(os.path.join(OUT, name), 'w') as f:
        f.write(text)
    print(name, len(text.encode()))


def bounds_of(paths):
    b = [p.bounds for p in paths if list(p.segments)]
    return (min(x[0] for x in b), min(x[1] for x in b), max(x[2] for x in b), max(x[3] for x in b))


