def layer(gid):
    """[(paint, geometry)] in paint order, geometry unioned per paint."""
    order, geo = [], {}
    for g, paint in sp.collect(sp.ids[gid]):
        if paint not in geo:
            order.append(paint)
            geo[paint] = []
        geo[paint].append(g)
    if gid == 'hot-titan':  # the edge shade is ~0 over the centred figure: skip it, saves ~85 KB
        order = [p for p in order if p != 'url(#hotShade)']
    return [(p, F.translate(F.union(geo[p]), -ox, -oy)) for p in order]


def fill_attr(paint, alpha_name=None):
    if paint == 'url(#hotBg)':
        return f'android:fillColor="{argb(SPLASH_BG)}"', ''
    if paint.startswith('url('):
        gr = sp.gradient(paint)
        its = '\n'.join(f'                    <item android:offset="{o:g}" android:color="{argb(c, a)}" />'
                        for o, c, a in gr['stops'])
        inner = f'''
        <aapt:attr name="android:fillColor">
            <gradient
                android:startX="{gr['x1'] - ox:.1f}"
                android:startY="{gr['y1'] - oy:.1f}"
                android:endX="{gr['x2'] - ox:.1f}"
                android:endY="{gr['y2'] - oy:.1f}"
                android:type="linear">
{its}
            </gradient>
        </aapt:attr>
    '''
        return '', inner
    return f'android:fillColor="{argb(paint)}"', ''


def path_xml(name, paint, geom, alpha, indent='        '):
    attr, inner = fill_attr(paint)
    a = f'\n{indent}    android:fillAlpha="{alpha:g}"' if alpha != 1 else ''
    d = F.to_d(geom, 1)
    if len(d) > 30000:  # aapt2 cannot store a UTF-8 string over 32 767 bytes: drop the decimals
        d = F.to_d(geom, 0)
    assert len(d) < 32000, (name, len(d))
    head = f'{indent}<path\n{indent}    android:name="{name}"{a}\n{indent}    android:pathData="{d}"'
    if attr:
        head += f'\n{indent}    {attr}'
    if inner:
        inner = inner.replace('\n        ', '\n' + indent + '    ').rstrip() + '\n'
        return head + '>\n' + inner + f'{indent}</path>'
    return head + ' />'


