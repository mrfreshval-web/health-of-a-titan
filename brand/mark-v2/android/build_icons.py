# SVG previews of the AVD at t = 0, 350, 700, 1000 ms (same geometry and paints)
def ease(t, c):  # cubic-bezier y(x) via bisection
    x1, y1, x2, y2 = c

    def bz(a, b, s):
        return 3 * a * s * (1 - s) ** 2 + 3 * b * s * s * (1 - s) + s ** 3
    lo, hi = 0.0, 1.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if bz(x1, x2, mid) < t:
            lo = mid
        else:
            hi = mid
    return bz(y1, y2, lo)


def svg_fill(paint, idx):
    if paint == 'url(#hotBg)':
        return SPLASH_BG, ''
    if paint.startswith('url('):
        gr = sp.gradient(paint)
        st = ''.join(f'<stop offset="{o}" stop-color="{c}" stop-opacity="{a}"/>' for o, c, a in gr['stops'])
        return f'url(#g{idx})', (f'<linearGradient id="g{idx}" gradientUnits="userSpaceOnUse" x1="{gr["x1"] - ox}" '
                                 f'y1="{gr["y1"] - oy}" x2="{gr["x2"] - ox}" y2="{gr["y2"] - oy}">{st}</linearGradient>')
    return paint, ''


for t in (0, 350, 700, 1000):
    ring_a = 0.2 + 0.8 * min(1, t / 800)
    tit_a = max(0, min(1, (t - 450) / 550))
    sweep = 0 if t < 120 else ease(min(1, (t - 120) / 780), (0.45, 0, 0.25, 1))
    xr = X0 + 0.1 + (X1 - X0 - 0.1) * sweep
    defs, body, idx = [], [], 0
    for key in ('ring', 'pulse', 'columns', 'titan', 'seams'):
        for n, p, g, a in paths[key]:
            idx += 1
            fill, d = svg_fill(p, idx)
            defs.append(d)
            alpha = ring_a if key == 'ring' else tit_a if key == 'titan' else 1
            clip = ' clip-path="url(#rv)"' if key in ('pulse', 'columns', 'seams') else ''
            body.append(f'<path{clip} fill="{fill}" fill-opacity="{alpha}" d="{F.to_d(g, 1)}"/>')
    write(f'preview_splash_{t}.svg', f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SV} {SV}"><defs>{"".join(defs)}'
          f'<clipPath id="rv"><rect x="{X0}" y="0" width="{xr - X0}" height="{SV}"/></clipPath></defs>'
          f'<rect width="{SV}" height="{SV}" fill="{SPLASH_BG}"/>{"".join(body)}'
          f'<circle cx="{SV / 2}" cy="{SV / 2}" r="{SV / 3}" fill="none" stroke="#f0f" stroke-width="4" stroke-dasharray="20 20"/></svg>')
