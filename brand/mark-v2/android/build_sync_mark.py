"""Builds the geometry of the animated sync mark (HotSyncMark) for Compose.

usage: build_sync_mark.py <brand/mark-v2 dir> <out .kt file>

The sync animation draws the mark piece by piece, so it needs the parts separately: the left
and right column and the titan as filled silhouettes (from icon/ic_stat_hot.svg, the same
reduction as the notification icon and the top-bar glyph), the ring (centre and radius of the
master, README §1) and the pulse polyline (source/geom.json). Everything stays in the master's
coordinate space (viewBox of hot-master.svg), so the parts line up exactly as on the icon.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svgflat as F  # noqa: E402

SRC, OUT = sys.argv[1], sys.argv[2]
CX, CY, R = 1024.2, 1023.0, 940.0
AXIS = 1024.1

stat = F.Doc(os.path.join(SRC, 'icon/ic_stat_hot.svg'))
outer = [e for e in stat.root if F.tag(e) == 'g'][0]
columns_g, titan_g = [e for e in outer if F.tag(e) == 'g'][:2]

columns = F.union([g for g, _ in stat.collect(columns_g)])
titan = F.union([g for g, _ in stat.collect(titan_g)])

left, right = [], []
for c in columns.contours:
    p = F.pathops.Path()
    c.draw(p.getPen())
    (left if p.bounds[2] < AXIS else right).append(p)
left, right = F.union(left), F.union(right)

geom = json.load(open(os.path.join(SRC, 'source', 'geom.json')))
pulse = [[(round(x, 1), round(y, 1)) for x, y in seg['pts']] for seg in geom['pulse']]


def kt_points(seg):
    return 'floatArrayOf(' + ', '.join(f'{x:g}f, {y:g}f' for x, y in seg) + ')'


def kt_string(d):
    # Kotlin constant strings: split into chunks so no single line gets absurdly long.
    chunks = [d[i:i + 160] for i in range(0, len(d), 160)]
    return '\n'.join(f'        "{c}" +' for c in chunks)[:-2]


def centre_x(p):
    b = p.bounds
    return (b[0] + b[2]) / 2


kt = f'''package com.healthofatitan.app.core.ui.component

/*
 * Geometry of the HoT mark for the animated sync mark ([HotSyncMark]), in the coordinate space
 * of brand/mark-v2/master/hot-master.svg. Generated by brand/mark-v2/android/build_sync_mark.py
 * from icon/ic_stat_hot.svg and source/geom.json — do not edit by hand.
 */
internal object HotMarkGeometry {{
    const val RING_CX = {CX}f
    const val RING_CY = {CY}f
    const val RING_R = {R}f
    const val PULSE_Y = {pulse[0][0][1]:g}f

    /** Horizontal centres of the parts: the pulse «lights» each one as it passes. */
    const val LEFT_COLUMN_X = {centre_x(left):.1f}f
    const val TITAN_X = {centre_x(titan):.1f}f
    const val RIGHT_COLUMN_X = {centre_x(right):.1f}f

    /** Vertical middle of the columns, for their glow. */
    const val COLUMNS_MID_Y = {(left.bounds[1] + left.bounds[3]) / 2:.1f}f
    const val TITAN_MID_Y = {(titan.bounds[1] + titan.bounds[3]) / 2:.1f}f

    /** The pulse in four visible pieces (between them it runs behind a column or the titan). */
    val PULSE: List<FloatArray> = listOf(
{chr(10).join('        ' + kt_points(s) + ',' for s in pulse)}
    )

    const val LEFT_COLUMN =
{kt_string(F.to_d(left, 0))}

    const val RIGHT_COLUMN =
{kt_string(F.to_d(right, 0))}

    const val TITAN =
{kt_string(F.to_d(titan, 0))}
}}
'''
with open(OUT, 'w') as f:
    f.write(kt)
print(OUT, len(kt.encode()), 'bytes; titan d', len(F.to_d(titan, 0)), 'columns', len(F.to_d(left, 0)), len(F.to_d(right, 0)))
