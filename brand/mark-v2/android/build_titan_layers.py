"""Builds the Titan of mark v2 as separate layers for the «Титаниум» scenes (A37 §3, §13).

usage: build_titan_layers.py <brand/mark-v2 dir> <android res/drawable dir>

The scene needs the parts of the mark apart, so that the columns can move and the Titan can
arrive (sync «Титан приходит»), be lit by the mode (Рассвет, Сегодня) and stand in a ring that
closes (Печать). The layers are cut from master/hot-master-transparent.svg exactly as
docs/design/concept-v3/src/titan.js does it — the same traced figure R1, never redrawn:

  titan_line            hot-titan-art                      the line art of the figure
  titan_knockout        hot-titan-knockout minus the hands the glass behind the lines
  titan_column_left_*   hot-columns-art / -knockout, x < 1024
  titan_column_right_*  the same, x ≥ 1024
  titan_glyph_*         the filled silhouettes of icon/ic_stat_hot.svg (the same reduction as
                        the notification icon) for sizes under ~120 dp, where line art breaks up

Every layer is a VectorDrawable in the master's 2048 × 2048 space, filled white: Compose tints
it (line of light = gradient through SrcIn), so all layers line up and the theme decides the
colour. The ring and the pulse are drawn in code from the same geometry (HotMarkGeometry).
Paths are split under aapt2's 32 KB string limit.
"""
import os
import sys

import pathops

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svgflat as F  # noqa: E402

SRC, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)
AXIS = 1024.0
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
WHITE = {'fill': '#fff', 'stroke': '#fff'}


def rect(x0, y0, x1, y1):
    p = pathops.Path()
    p.moveTo(x0, y0)
    p.lineTo(x1, y0)
    p.lineTo(x1, y1)
    p.lineTo(x0, y1)
    p.close()
    return p


LEFT = rect(-10, -10, AXIS, 2058)
RIGHT = rect(AXIS, -10, 2058, 2058)
# titan.js `tt-nohands`: the hands lie on the capitals, the glass must not cover the columns there.
HANDS = F.union([rect(495, 617, 648, 823), rect(1400, 617, 1553, 823)])

master = F.Doc(os.path.join(SRC, 'master/hot-master-transparent.svg'))


def group(gid):
    return F.union([g for g, _ in master.collect(master.ids[gid], dict(WHITE))])


titan_line = group('hot-titan-art')
titan_knock = F.op(group('hot-titan-knockout'), HANDS, pathops.PathOp.DIFFERENCE)
columns_line = group('hot-columns-art')
columns_knock = group('hot-columns-knockout')

stat = F.Doc(os.path.join(SRC, 'icon/ic_stat_hot.svg'))
outer = [e for e in stat.root if F.tag(e) == 'g'][0]
columns_g, titan_g = [e for e in outer if F.tag(e) == 'g'][:2]
glyph_columns = F.union([g for g, _ in stat.collect(columns_g)])
glyph_titan = F.union([g for g, _ in stat.collect(titan_g)])


def side(p, half):
    return F.op(p, half, pathops.PathOp.INTERSECTION)


LAYERS = [
    ('titan_line', titan_line, 'line art of the Titan (hot-titan-art)'),
    ('titan_knockout', titan_knock, 'glass knockout of the Titan, hands left open (hot-titan-knockout)'),
    ('titan_column_left_line', side(columns_line, LEFT), 'left column, line art (hot-columns-art)'),
    ('titan_column_right_line', side(columns_line, RIGHT), 'right column, line art (hot-columns-art)'),
    ('titan_column_left_knockout', side(columns_knock, LEFT), 'left column, glass knockout'),
    ('titan_column_right_knockout', side(columns_knock, RIGHT), 'right column, glass knockout'),
    ('titan_glyph_titan', glyph_titan, 'Titan silhouette for small sizes (icon/ic_stat_hot.svg)'),
    ('titan_glyph_column_left', side(glyph_columns, LEFT), 'left column silhouette for small sizes'),
    ('titan_glyph_column_right', side(glyph_columns, RIGHT), 'right column silhouette for small sizes'),
]

total = 0
for name, geom, what in LAYERS:
    parts = F.split(geom, nd=1)
    body = []
    for i, part in enumerate(parts):
        d = F.to_d(part, 1)
        if len(d) > 30000:
            d = F.to_d(part, 0)
        assert len(d) < 32000, (name, i, len(d))
        body.append(f'    <path\n        android:name="{name}_{i}"\n        android:fillColor="#FFFFFFFF"\n'
                    f'        android:pathData="{d}" />')
    xml = HEADER + f'''<!-- «Титаниум» scene layer: {what}.
     Mark v2 space 2048 × 2048, white; tinted in Compose (TitanScene). Generated by
     brand/mark-v2/android/build_titan_layers.py from brand/mark-v2 — do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools"
    android:width="2048dp"
    android:height="2048dp"
    android:viewportWidth="2048"
    android:viewportHeight="2048"
    tools:ignore="VectorPath,VectorRaster">
{chr(10).join(body)}
</vector>
'''
    with open(os.path.join(OUT, name + '.xml'), 'w') as f:
        f.write(xml)
    total += len(xml.encode())
    print(name, len(parts), 'paths', len(xml.encode()), 'bytes', [round(v) for v in geom.bounds])
print('total', total)
